
public class h8 {
    public static void main(String[] args) {

        int result1 = 10 + 5 * 2;
        int result2 = (10 + 5) * 2;
        int result3 = 20 / 5 + 3 * 4;

        System.out.println("10 + 5 * 2 = " + result1);
        System.out.println("(10 + 5) * 2 = " + result2);
        System.out.println("20 / 5 + 3 * 4 = " + result3);

        System.out.println("\nOperator Precedence:");
        System.out.println("1. Brackets");
        System.out.println("2. Multiplication/Division");
        System.out.println("3. Addition/Subtraction");
    }
}